"""도메인 온톨로지 의미 계층 서비스.

Neptune을 데이터 관계의 '온톨로지(의미) 계층'으로 사용한다.

- 스키마/시드(최상위 도메인)는 ``app/ontology/domain_ontology.ttl`` 에 사전 정의되고
  ``scripts/load_ontology.py`` 로 Neptune에 적재된다 (고정).
- 데이터셋이 어떤 도메인에 속하는지(``belongsToDomain``)는 적재 시점에 자동 연결된다 (가변).
- 시드에 없는 도메인이 들어오면 신규 ``dm:Domain`` 노드를 생성하고
  ``autoGenerated=true`` 로 표시한다.
"""

import logging
from urllib.parse import quote

from app.clients.neptune import NeptuneClient, get_neptune_client
from app.config import settings

logger = logging.getLogger(__name__)

_DM = settings.DATASET_RDF_NAMESPACE

# 시드 도메인 별칭 → 표준 코드 (domain_ontology.ttl 에 사전 정의된 최상위 도메인).
# 자동 분류 결과의 한글/영문 도메인 문자열을 표준 코드로 정규화한다.
_DOMAIN_ALIASES: dict[str, str] = {
    "medical": "medical", "의료": "medical", "병원": "medical", "health": "medical",
    "legal": "legal", "법률": "legal", "법": "legal", "판례": "legal", "law": "legal",
    "broadcast": "broadcast", "방송": "broadcast", "콘텐츠": "broadcast",
    "방송/콘텐츠": "broadcast", "content": "broadcast", "media": "broadcast",
}

_SEED_DOMAIN_CODES = set(_DOMAIN_ALIASES.values())


class OntologyService:
    """Neptune 도메인 온톨로지 계층 관리 서비스."""

    def __init__(self, neptune_client: NeptuneClient | None = None):
        self.neptune = neptune_client or get_neptune_client()

    def link_dataset_to_domain(self, table_name: str, domain: str) -> str:
        """Dataset 노드를 도메인 개념에 ``belongsToDomain`` 으로 연결.

        도메인 문자열을 시드 코드로 정규화하고, 시드에 없으면 신규 도메인 노드를
        생성한다. 기존 연결은 제거 후 재연결하여 멱등성을 보장한다.

        Args:
            table_name: 데이터셋(테이블) 식별자
            domain: 스키마 분석/사용자 입력으로 얻은 도메인 문자열

        Returns:
            연결된 표준 도메인 코드
        """
        code = self._resolve_domain_code(domain)
        dataset_uri = f"<{_DM}dataset/{quote(table_name)}>"
        domain_uri = f"<{_DM}domain/{quote(code)}>"
        is_new = code not in _SEED_DOMAIN_CODES

        new_domain_triples = ""
        if is_new:
            label = (domain or code).replace("\\", "\\\\").replace('"', '\\"')
            new_domain_triples = (
                f"{domain_uri} rdf:type dm:Domain ; "
                f'rdfs:label "{label}" ; '
                f'dm:domainCode "{code}" ; '
                f'dm:autoGenerated "true"^^xsd:boolean .'
            )

        update = f"""
        PREFIX dm: <{_DM}>
        PREFIX rdf: <http://www.w3.org/1999/02/22-rdf-syntax-ns#>
        PREFIX rdfs: <http://www.w3.org/2000/01/rdf-schema#>
        PREFIX xsd: <http://www.w3.org/2001/XMLSchema#>

        DELETE {{ {dataset_uri} dm:belongsToDomain ?d . }}
        WHERE  {{ OPTIONAL {{ {dataset_uri} dm:belongsToDomain ?d . }} }} ;

        INSERT DATA {{
            {new_domain_triples}
            {dataset_uri} dm:belongsToDomain {domain_uri} .
        }}
        """
        self.neptune.execute_update(update)
        logger.info(
            f"[Ontology] '{table_name}' → 도메인 '{code}' 연결 (신규 도메인={is_new})"
        )
        return code

    def get_domains(self) -> list[dict]:
        """등록된 도메인 목록과 소속 데이터셋 수를 반환 (데이터셋 수 내림차순)."""
        query = f"""
        PREFIX dm: <{_DM}>
        PREFIX rdf: <http://www.w3.org/1999/02/22-rdf-syntax-ns#>
        PREFIX rdfs: <http://www.w3.org/2000/01/rdf-schema#>

        SELECT ?code ?label (COUNT(?ds) AS ?datasetCount) WHERE {{
            ?domain rdf:type dm:Domain ;
                    dm:domainCode ?code .
            OPTIONAL {{ ?domain rdfs:label ?label }}
            OPTIONAL {{ ?ds dm:belongsToDomain ?domain }}
        }}
        GROUP BY ?code ?label
        ORDER BY DESC(?datasetCount)
        """
        try:
            resp = self.neptune.execute_query(query)
            return [
                {
                    "code": b["code"]["value"],
                    "label": b.get("label", {}).get("value"),
                    "dataset_count": int(b["datasetCount"]["value"]),
                }
                for b in resp.get("results", {}).get("bindings", [])
            ]
        except Exception as e:
            logger.warning(f"[Ontology] 도메인 조회 실패: {e}")
            return []

    @staticmethod
    def _resolve_domain_code(domain: str) -> str:
        """도메인 문자열을 표준 코드로 정규화. 미지정은 'general', 미등록은 슬러그화."""
        key = (domain or "").strip()
        if not key:
            return "general"

        lowered = key.lower()
        for alias, code in _DOMAIN_ALIASES.items():
            if lowered == alias.lower():
                return code

        # 시드에 없는 신규 도메인: 원문을 그대로 코드로 사용 (URI는 호출부에서 인코딩)
        return key


ontology_service = OntologyService()
